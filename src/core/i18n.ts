// 키를 따로 만들지 않고 영문 원문을 그대로 키로 쓴다. 사전에 없으면 영문이 그대로 나가므로
// 번역이 빠져도 화면이 깨지지 않는다. 원문을 고치면 사전 항목도 같이 고쳐야 한다.
